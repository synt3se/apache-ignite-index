package ru.nsu.fit.sberlab.vectorindex.common.dto;

/** Причины, по которым ответ не {@link SearchStatus#COMPLETE}. Проверяются все, а не только число партиций. */
public enum Incompleteness {
    /** Ожидаемая партиция не обработана: нет владельца, runtime, индекса, загрузка, отказ, бюджет. */
    MISSING_PARTITIONS,
    /** Обработанная партиция с известным пробелом относительно источника (ожидающая сверка). */
    KNOWN_GAP,
    /** Исчерпан бюджет запроса. */
    TIMED_OUT,
    /** Назначенный владелец не ответил, ответил ошибкой или пустым ответом. */
    NODE_NO_RESPONSE,
    /** Один ключ пришёл из двух ответов — нарушение назначения партиций. */
    DUPLICATE_KEYS
}
