package ru.nsu.fit.sberlab.vectorindex.common.dto;

/**
 * Статус выполнения поиска. {@code COMPLETE} означает, что заявленный поиск выполнен по всем
 * ожидаемым партициям без известных пробелов, в бюджете и без нарушений назначения.
 * Точность ANN (recall) и свежесть относительно всех записей источника — отдельные свойства,
 * статус их не утверждает.
 */
public enum SearchStatus {
    COMPLETE,
    /** Есть причины неполноты ({@link Incompleteness}), попадания возвращены. */
    PARTIAL,
    /** Неполный ответ при {@code allowPartial=false}: попадания не возвращаются. */
    FAILED
}
