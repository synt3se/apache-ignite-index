package ru.nsu.fit.sberlab.vectorindex.core;

/**
 * Метрика расстояния индекса. Во всех путях (точный перебор, rerank кандидатов ANN,
 * дельта, слияние партиций) действует одно правило: меньше — ближе.
 */
public enum Metric {
    /**
     * {@code 1 − cos(a, b)}. Векторы нормализуются при приёме, поэтому расстояние
     * считается как {@code 1 − dot}. Вектор с нулевой нормой не нормализуется и даёт
     * расстояние 1.0 до любого другого (текущий контракт {@code zeroNormProducesFiniteDistance}).
     */
    COSINE,

    /** {@code Σ(aᵢ − bᵢ)²} без извлечения корня. */
    SQUARED_L2
}
