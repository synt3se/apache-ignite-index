package ru.nsu.fit.sberlab.vectorindex.core;

/** Состояние поисковой структуры базы (оптимизация отдельна от доступности данных). */
public enum OptimizationState {
    /** База без структуры алгоритма: поиск по ней — точный перебор. */
    NOT_BUILT,
    /** Есть незавершённый токен сборки. */
    BUILDING,
    /** База построена алгоритмом. */
    BUILT,
    /** Последняя сборка завершилась ошибкой; данные доступны через frozen-слои, повтор с задержкой. */
    FAILED
}
