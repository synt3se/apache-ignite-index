package ru.nsu.fit.sberlab.vectorindex.core;

/** Почему адаптер просит сверку с источником. */
public enum RepairReason {
    /** Уведомление об изменении не принято очередью применения. */
    APPLIER_OVERFLOW,
    /** Ожидаемая ошибка при чтении источника или применении изменения. */
    APPLY_FAILED,
    /** Скан завершился ошибкой. */
    SCAN_FAILED,
    /** Явный запрос (администратор, тест, массовая загрузка). */
    MANUAL
}
