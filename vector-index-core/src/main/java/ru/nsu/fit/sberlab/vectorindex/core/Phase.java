package ru.nsu.fit.sberlab.vectorindex.core;

/** Фаза эпизода владения партицией. */
public enum Phase {
    /** Начальная загрузка: изменения принимаются, но полного вида ещё нет. Поиск не засчитывается. */
    LOADING,
    /** Опубликован результат скана; вид доступен поиску (возможна ожидающая сверка — см. готовность). */
    READY,
    /** Эпизод завершён: изменения — {@code CLOSED}, публикации — {@code REJECTED_STALE}. */
    CLOSED
}
